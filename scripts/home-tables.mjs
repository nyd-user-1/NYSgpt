#!/usr/bin/env node
/**
 * Builds lib/home-tables.ts: the home page's Tables set (Brendan, 2026-11-19).
 * The 100 largest tables by record count in the catalog copy the site carries
 * (public/home-catalog/catalog.json), one box each. A table name that repeats
 * in another database is taken once, since the plate keys a box by its set and
 * name. Run from the repo root:  node scripts/home-tables.mjs
 */
import fs from 'fs'

const c = JSON.parse(fs.readFileSync('public/home-catalog/catalog.json', 'utf8'))
const compact = n => {
  const f = (v, s) => `${+v.toFixed(v >= 100 ? 0 : 1)}${s}`
  return n >= 1e9 ? f(n / 1e9, 'B') : n >= 1e6 ? f(n / 1e6, 'M') : n >= 1e3 ? f(n / 1e3, 'K') : String(n)
}
const clip = (s, n = 150) => {
  s = String(s ?? '').replace(/\s+/g, ' ').trim()
  return s.length > n ? `${s.slice(0, n - 1).replace(/[\s,;:.]+\S*$/, '')}…` : s
}
const db = t => (typeof t.d === 'number' ? c.dbs[t.d] : t.d)
const seen = new Set()
const boxes = []
for (const t of c.tables.filter(t => t.r != null).sort((a, b) => b.r - a.r)) {
  if (boxes.length >= 100) break
  if (seen.has(t.t)) continue
  seen.add(t.t)
  boxes.push({ kind: 'tables', title: t.t, group: db(t), body: clip(t.a) || `${compact(t.r)} records in ${db(t)}.`, foot: compact(t.r), accent: '', icon: 'table' })
}
fs.writeFileSync(
  'lib/home-tables.ts',
  `/**
 * The home page's Tables set: the 100 largest tables in the site's catalog copy. GENERATED by
 * scripts/home-tables.mjs on ${new Date().toISOString().slice(0, 10)}; do not edit by hand, run the script again.
 * \`group\` is the table's database, which the catalog view opens on.
 */
import type { Box } from './home-boxes'

export const TABLE_BOXES: Box[] = ${JSON.stringify(boxes, null, 1)}
`,
)
console.log('written lib/home-tables.ts', boxes.length, 'boxes; largest', boxes[0]?.title, boxes[0]?.foot, '; smallest', boxes[boxes.length - 1]?.title, boxes[boxes.length - 1]?.foot)
